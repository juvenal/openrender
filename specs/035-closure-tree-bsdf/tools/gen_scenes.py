#!/usr/bin/env python3
"""Spec 035, tasks.md T103: generates the 24 determinism-sweep scenes of research R22 under examples/rib/tests/.

    python3 specs/035-closure-tree-bsdf/tools/gen_scenes.py [--check]

Four scenes (closures-modes, closures-bxdf-interim, closures-arealight, closures-instancing), each under the three camera hiders (reyes,
zbuffer, raytrace) and the two shader formats (rslo, and slo with the `-slo` suffix, as spec 057's scenes name them): 4 x 3 x 2 = 24. The
output is deterministic: a second run writes the same bytes (--check compares instead of writing and exits 1 on a difference). The scenes use
shipped shaders only, which are never closure capable (FR-017), so they exercise the interim behaviours (IR-017, IR-026) across threads, hiders,
formats and a -P:2 loopback; the closure path itself is observed by the in-process tests of tests/closures.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(ROOT, "examples", "rib", "tests")

HIDERS = ["reyes", "zbuffer", "raytrace"]
FORMATS = [("rslo", ""), ("slo", "-slo")]

LIGHT = 'LightSource "distantlight" 1 "intensity" 1.2 "from" [0 0 0] "to" [0.3 -0.3 1]'


def header(name, text):
    return ("##RenderMan RIB-Structure 1.0\n"
            "# Spec 035 (closure tree and BSDF), generated by specs/035-closure-tree-bsdf/tools/gen_scenes.py: do not edit.\n"
            + "".join("# " + line + "\n" for line in text.strip().split("\n")))


def preamble(hider, fmt):
    lines = ["version 3.03"]
    if hider == "raytrace":
        lines.append('Hider "raytrace" "jitter" [0]')
    else:
        lines.append('Hider "%s"' % hider)
    lines.append("PixelSamples 2 2")
    lines.append('PixelFilter "box" 1 1')
    lines.append('Quantize "rgba" 0 0 0 0')
    if fmt == "slo":
        lines.append('Option "shaderformat" "default" ["slo"]')
    return lines


def camera(display, fov=40, back=6):
    return ['Display "%s" "file" "rgba"' % display,
            "Format 16 16 1",
            'Projection "perspective" "fov" [%d]' % fov,
            "Clipping 0.1 1000",
            "Translate 0 0 %d" % back]


def sphere_at(x, y, body, color="0.8 0.8 0.8"):
    return ["  AttributeBegin",
            "    Translate %g %g 0" % (x, y),
            "    Color [%s]" % color] + ["    " + b for b in body] + ["    Sphere 1 -1 1 360", "  AttributeEnd"]


def scene_modes(name, hider, fmt):
    desc = ("closures-modes: Option \"shade\" \"closuremode\" [\"both\"] for the scene, a nested attribute \"closures\" and a nested attribute \"color\".\n"
            "The shipped surfaces are never closure capable (FR-017): under both and closures they render as color, with one IR-017 warning per\n"
            "(shader, mode) per frame. The image is the same in the three modes.")
    out = preamble(hider, fmt) + camera(name + ".tif")
    out.append('Option "shade" "closuremode" ["both"]')
    out += ["WorldBegin", "  " + LIGHT]
    out += sphere_at(-2.2, 0, ['Surface "plastic"'], "0.9 0.3 0.2")
    out += sphere_at(0, 0, ['Attribute "shade" "closuremode" ["closures"]', 'Surface "matte"'], "0.2 0.8 0.3")
    out += sphere_at(2.2, 0, ['Attribute "shade" "closuremode" ["color"]', 'Surface "plastic"'], "0.2 0.3 0.9")
    out.append("WorldEnd")
    return header(name, desc) + "\n".join(out) + "\n", [name + ".tif"]


def scene_bxdf(name, hider, fmt):
    desc = ("closures-bxdf-interim: the four Bxdfs and the Surface/Bxdf order in nested blocks (IR-026: with no consumer a governing Bxdf renders\n"
            "the substitute surface and warns once per Bxdf name). Frame 1 has no Surface before WorldBegin, so the substitute is the\n"
            "defaultsurface RiWorldBegin binds (A'); frame 2 gives a Surface before WorldBegin, so the substitute is the no-shader path and the\n"
            "pre-world Surface is never used.")
    out = preamble(hider, fmt)
    out.append("FrameBegin 1")
    out += camera(name + ".tif", 45, 8)
    out += ["WorldBegin", "  " + LIGHT]
    out += sphere_at(-2.4, 1.2, ['Bxdf "diffuse" "float Kd" [0.9]'], "0.9 0.3 0.2")
    out += sphere_at(0, 1.2, ['Bxdf "plastic" "float roughness" [0.2]'], "0.2 0.8 0.3")
    out += sphere_at(2.4, 1.2, ['Bxdf "conductor"'], "0.8 0.8 0.3")
    out += sphere_at(-2.4, -1.2, ['Bxdf "dielectric" "float ior" [1.4]'], "0.3 0.3 0.9")
    out += sphere_at(0, -1.2, ['Surface "matte"', 'Bxdf "diffuse"'], "0.8 0.5 0.2")      # Bxdf bound last: the Bxdf governs
    out += sphere_at(2.4, -1.2, ['Bxdf "plastic"', 'Surface "plastic"'], "0.5 0.2 0.8")   # Surface bound last: the Surface governs
    out += ["WorldEnd", "FrameEnd", "FrameBegin 2"]
    out += camera(name + "-b.tif", 45, 8)
    out += ['Surface "matte"', "WorldBegin", "  " + LIGHT]
    out += sphere_at(-1.2, 0, ['Bxdf "conductor"'], "0.8 0.8 0.3")
    out += sphere_at(1.2, 0, ['Bxdf "dielectric"'], "0.3 0.3 0.9")
    out += ["WorldEnd", "FrameEnd"]
    return header(name, desc) + "\n".join(out) + "\n", [name + ".tif", name + "-b.tif"]


def scene_arealight(name, hider, fmt):
    desc = ("closures-arealight: a bound area light (AreaLightSource) over two receivers, one in mode color and one in mode closures, side by side and\n"
            "not seen by each other's shadow or reflection rays. The shipped receiver surface is not closure capable, so both render as color\n"
            "and the closures one warns once (IR-017).")
    out = preamble(hider, fmt) + camera(name + ".tif", 50, 9)
    out += ["WorldBegin",
            "  AttributeBegin",
            '    AreaLightSource "arealight" 1 "float intensity" [8]',
            '    Surface "constant"',
            '    Polygon "P" [-1 3 -1  1 3 -1  1 3 1  -1 3 1]',
            "  AttributeEnd"]
    out += sphere_at(-2.5, 0, ['Attribute "shade" "closuremode" ["color"]', 'Surface "matte"'], "0.9 0.9 0.9")
    out += sphere_at(2.5, 0, ['Attribute "shade" "closuremode" ["closures"]', 'Surface "matte"'], "0.9 0.9 0.9")
    out.append("WorldEnd")
    return header(name, desc) + "\n".join(out) + "\n", [name + ".tif"]


def scene_instancing(name, hider, fmt):
    desc = ("closures-instancing: ObjectBegin/ObjectInstance carrying the mode and a Bxdf. An instance takes the attributes current at\n"
            "ObjectInstance (RISpec 3.2 section 5.10), so the mode and the Bxdf are bound at the instance, never inside the object block (a Bxdf\n"
            "statement there is refused).")
    out = preamble(hider, fmt) + camera(name + ".tif", 40, 7)
    out += ["WorldBegin", "  " + LIGHT,
            "  ObjectBegin 1",
            "    Sphere 1 -1 1 360",
            "  ObjectEnd",
            "  AttributeBegin",
            "    Translate -1.6 0 0",
            "    Color [0.9 0.3 0.2]",
            '    Attribute "shade" "closuremode" ["both"]',
            '    Bxdf "plastic"',
            "    ObjectInstance 1",
            "  AttributeEnd",
            "  AttributeBegin",
            "    Translate 1.6 0 0",
            "    Color [0.2 0.3 0.9]",
            '    Attribute "shade" "closuremode" ["closures"]',
            '    Surface "matte"',
            "    ObjectInstance 1",
            "  AttributeEnd",
            "WorldEnd"]
    return header(name, desc) + "\n".join(out) + "\n", [name + ".tif"]


SCENES = [("closures-modes", scene_modes), ("closures-bxdf-interim", scene_bxdf),
          ("closures-arealight", scene_arealight), ("closures-instancing", scene_instancing)]


def generate():
    files = {}
    outputs = {}
    for base, fn in SCENES:
        for hider in HIDERS:
            for fmt, suffix in FORMATS:
                name = "%s-%s%s" % (base, hider, suffix)
                text, outs = fn(name, hider, fmt)
                files[name + ".rib"] = text
                outputs[name] = outs
    return files, outputs


def main():
    files, outputs = generate()
    check = "--check" in sys.argv
    bad = 0
    for fname, text in sorted(files.items()):
        path = os.path.join(OUT, fname)
        if check:
            if not os.path.exists(path) or open(path).read() != text:
                print("differs: " + fname)
                bad += 1
        else:
            with open(path, "w") as f:
                f.write(text)
    if "--list" in sys.argv:
        for name in sorted(outputs):
            print(name, *outputs[name])
    if check:
        sys.exit(1 if bad else 0)
    print("%d scenes" % len(files))


main()
