#!/usr/bin/env python3
"""Spec 056 scene generator (tasks.md T022).

Writes examples/rib/tests/<family>-<hider>[-slo].rib (and the no-volume twins <family>-none-<hider>[-slo].rib) and
tests/visual/volume-probes.cmake (one add_volume_probe() call per probed pixel, with the hand-computed expected values
from the same numbers the RIBs are built from). The generated files are checked in, as spec 021's gen_scenes.py outputs
were (CLAUDE.md gotcha 21): a regeneration is diffed.

  python3 specs/056-volume-shader-segments/tools/gen_scenes.py [--check] [--out <scratch dir>]

--check writes nothing and exits 1 if a file would change.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(HERE, "families"))

import common  # noqa: E402
import slab, reflection, transmission, shadow, gather, incident, randomfog, glasssphere, atmosphere, csgfragment  # noqa: E402

FAMILIES = [slab, reflection, transmission, shadow, gather, incident, randomfog, glasssphere, atmosphere, csgfragment]


def main():
    check = "--check" in sys.argv
    out_dir = os.path.join(ROOT, "examples", "rib", "tests")
    ppath = os.path.join(ROOT, "tests", "visual", "volume-probes.cmake")
    if "--out" in sys.argv:   # a dry run into a scratch directory: --out <dir>
        out_dir = sys.argv[sys.argv.index("--out") + 1]
        ppath = os.path.join(out_dir, "volume-probes.cmake")
    scenes = []
    for f in FAMILIES:
        scenes += f.scenes()
    names = [s.name for s in scenes]
    assert len(names) == len(set(names)), "duplicate scene names: %s" % sorted(set(n for n in names if names.count(n) > 1))

    changed = 0
    for s in scenes:
        path = os.path.join(out_dir, s.name + ".rib")
        text = common.rib_text(s)
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            changed += 1
            if not check:
                open(path, "w").write(text)

    # the probe registrations (generated: the macro lives in volume-scenes.cmake)
    lines = ["# GENERATED by specs/056-volume-shader-segments/tools/gen_scenes.py -- do not edit; regenerate and diff.",
             "# add_volume_probe(<scene> <x> <y> <tolerance> <value>...): one pixel of a float scene, read back with test_pixel_probe.",
             ""]
    for p in common.PROBES:
        lines.append("add_volume_probe(%s %d %d %g %s)" % (p.scene, p.x, p.y, p.tol, " ".join("%.7g" % v for v in p.values)))
    probes = "\n".join(lines) + "\n"
    old = open(ppath).read() if os.path.exists(ppath) else None
    if old != probes:
        changed += 1
        if not check:
            open(ppath, "w").write(probes)

    # the determinism sweep entries (tests/visual/determinism-scenes.cmake, a contiguous block at the end of the file)
    sweep = ["# --- Spec 056 (volume shader segments): the generated scenes, GENERATED by specs/056-volume-shader-segments/tools/gen_scenes.py ---",
             "# One entry per scene file, every one of them a non-GI visual or probe scene (gather() here is not the irradiance cache).",
             "# BEGIN spec 056"]
    for s in scenes:
        sweep.append("add_determinism_sweep(%s examples/rib/tests/%s.rib %s.tif)" % (s.name, s.name, s.name))
    sweep.append("# END spec 056")
    dpath = os.path.join(ROOT, "tests", "visual", "determinism-scenes.cmake")
    if "--out" not in sys.argv:
        dtext = open(dpath).read()
        head = dtext.split("# --- Spec 056 (volume shader segments)")[0].rstrip("\n") + "\n"
        new_text = head + "\n".join(sweep) + "\n"
        if new_text != dtext:
            changed += 1
            if not check:
                open(dpath, "w").write(new_text)
    print("%d scenes, %d probes, %d file(s) %s" % (len(scenes), len(common.PROBES), changed, "would change" if check else "written"))
    for s in scenes:
        print("  " + s.name)
    return 1 if (check and changed) else 0


if __name__ == "__main__":
    sys.exit(main())
