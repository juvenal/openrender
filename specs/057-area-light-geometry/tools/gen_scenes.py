#!/usr/bin/env python3
"""Spec 057 scene generator (tasks.md T060): the closed-form probe scenes of the area-light geometry spec.

Writes examples/rib/tests/arealight-{probe,illuminate}-*.rib and tests/visual/arealight-probes.cmake (one
add_arealight_probe() call per probed pixel; the expected values and tolerances come from probe_expected.py, the same
numbers the RIBs are built from). The generated files are checked in (CLAUDE.md gotcha 21): a regeneration is diffed.

    python3 -I specs/057-area-light-geometry/tools/gen_scenes.py [--check]

--check writes nothing and exits 1 if a file would change.

Geometry (camera space, an orthographic camera at the origin looking along +z, `Format 8 8 1`, window [-1, 1]^2):
  receiver  the plane z = 4 spanning exactly the window, seen from the camera (so receiver u, v run over [0, 1] across
            the image: pixel (0, 0) has u = 0.0625)
  emitter   a quad in the plane x = 3, facing -x, outside the window: p0 (3,-1,1) p1 (3,-1,3) p2 (3,1,3) p3 (3,1,1), area 4
            (the globals probes use the same shape moved to y in [1, 3] so every coordinate is positive)
  light     AreaLightSource "<light>" 1 ... in an attribute block with the emitter, then `Illuminate 1 1` for the receiver
The scenes run on the default area-light sample count (16): Option "arealight" arrives with the controls (Phase 5).
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, HERE)
import probe_expected as pe  # noqa: E402

HIDERS = ["raytrace", "reyes", "zbuffer"]
OUT_RIB = os.path.join(ROOT, "examples", "rib", "tests")
OUT_CMAKE = os.path.join(ROOT, "tests", "visual", "arealight-probes.cmake")

files = {}      # path -> text
probes = []     # (test, scene, x, y, tol, channels or None, values)


def fmt(x):
    return repr(float(x))


def header(name, hider, slo, comment):
    lines = ["##RenderMan RIB-Structure 1.0", "# Spec 057 (area-light geometry), generated by specs/057-area-light-geometry/tools/gen_scenes.py: do not edit."]
    lines += ["# " + c if c else "#" for c in comment]
    lines.append("version 3.03")
    if slo:
        lines.append('Option "shaderformat" "default" ["slo"]')
    lines += [
        'Hider "%s" "jitter" [0]' % hider,
        "PixelSamples 1 1",
        'PixelFilter "box" 1 1',
        'Quantize "rgba" 0 0 0 0',
        'Display "%s.tif" "file" "rgba"' % name,
        "Format 8 8 1",
        'Projection "orthographic"',
        "Clipping 0.1 100",
    ]
    return lines


def poly(p):
    return "Polygon \"P\" [%s]" % "  ".join("%g %g %g" % tuple(v) for v in p)


EMITTER = [[3, -1, 1], [3, -1, 3], [3, 1, 3], [3, 1, 1]]            # N = -x
EMITTER_BACK = [[3, -1, 1], [3, 1, 1], [3, 1, 3], [3, -1, 3]]       # N = +x (the receivers are behind it)
EMITTER_HI = [[3, 1, 1], [3, 1, 3], [3, 3, 3], [3, 3, 1]]           # N = -x, y in [1, 3]: every coordinate positive
RECEIVER = [[-1, -1, 4], [1, -1, 4], [1, 1, 4], [-1, 1, 4]]         # N = +z; the receiver shaders face it to the viewer or not
WALL = [[1.5, -3, 0], [1.5, -3, 5], [1.5, 3, 5], [1.5, 3, 0]]       # x = 1.5, between the emitter and every receiver pixel


def body(light, light_params, emitter, receiver_shader, wall=None, emitter_extra=None, illuminate=True, bind=True):
    b = ["WorldBegin", "  AttributeBegin"]
    if bind:
        b.append('    AreaLightSource "%s" 1 %s' % (light, light_params))
    b.append('    Surface "constant"')
    b.append("    " + (emitter_extra or poly(emitter)))
    b.append("  AttributeEnd")
    if bind and illuminate:
        b.append("  Illuminate 1 1")
    elif bind:
        b.append("  Illuminate 1 0")
    if wall is not None:
        b.append("  AttributeBegin")
        if wall == "flagged":
            b.append('    Attribute "visibility" "int transmission" [1]')
        b.append('    Surface "matte"')
        b.append("    " + poly(WALL))
        b.append("  AttributeEnd")
    b.append("  AttributeBegin")
    b.append('    Surface "%s"' % receiver_shader)
    b.append("    " + poly(RECEIVER))
    b.append("  AttributeEnd")
    b.append("WorldEnd")
    return b


RECEIVER_LEFT = [[-1, -1, 4], [0, -1, 4], [0, 1, 4], [-1, 1, 4]]     # x < 0: pixels with a negative pixel-centre x
RECEIVER_RIGHT = [[0, -1, 4], [1, -1, 4], [1, 1, 4], [0, 1, 4]]      # x > 0


def body_controls(options, light_attrs, receivers):
    """The controls scenes (Phase 5): the shipped arealight over the quad probe geometry. `options`: Option lines (before WorldBegin);
    `light_attrs`: Attribute lines inside the light's scope, before its AreaLightSource; `receivers`: [(attribute lines, polygon)],
    each its own al_surface_matte block."""
    b = list(options)
    b += ["WorldBegin", "  AttributeBegin"]
    b += ["    " + a for a in light_attrs]
    b.append('    AreaLightSource "arealight" 1 "float intensity" [%g]' % pe.INTENSITY)
    b.append('    Surface "constant"')
    b.append("    " + poly(EMITTER))
    b.append("  AttributeEnd")
    b.append("  Illuminate 1 1")
    for (attrs, polygon) in receivers:
        b.append("  AttributeBegin")
        b += ["    " + a for a in attrs]
        b.append('    Surface "al_surface_matte"')
        b.append("    " + poly(polygon))
        b.append("  AttributeEnd")
    b.append("WorldEnd")
    return b


def add_scene(name, hider, slo, comment, lines):
    if slo:
        # GitHub #126: a .slo surface whose only lighting call is illuminance(P) gathers no light. The light is the .slo under test, so
        # the receiver is pinned to .rslo (the #123 harness does the same)
        lines = [x for l in lines for x in (['    Attribute "shade" "shaderformat" ["rslo"]', l] if l == '    Surface "al_surface_lightsum"' else [l])]
    files[os.path.join(OUT_RIB, name + ".rib")] = "\n".join(header(name, hider, slo, comment) + lines) + "\n"


def add_probe(test, scene, x, y, tol, values, channels=None):
    probes.append((test, scene, x, y, tol, channels, values))


def pixel_comment(rows):
    out = []
    for (i, j, e, s1, tol) in rows:
        out.append("  pixel (%d, %d): expected %.9f, tolerance %.9f (4 sigma_1 / sqrt(16), sigma_1 = %.9f)" % (i, j, e, tol, s1))
    return out


def main():
    check = "--check" in sys.argv
    pe.self_test()
    for slo in (False, True):
        sfx = "-slo" if slo else ""
        # ---- the quad probe: shipped arealight, closed-form irradiance, three hiders ---------------------------------
        rows = []
        for (i, j) in pe.PIXELS:
            x, y = pe.pixel_center(i, j)
            e, s1 = pe.pixel_value("arealight", pe.EMITTER, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.INTENSITY)
            rows.append((i, j, e, s1, pe.tolerance(s1, pe.SAMPLES)))
        for hider in HIDERS:
            name = "arealight-probe-quad-%s%s" % (hider, sfx)
            add_scene(name, hider, slo,
                      ["AreaLightProbe_QuadIrradiance: a Lambertian plane (al_surface_matte, z = 4) under one quad (x = 3, facing -x, 2 x 2)",
                       "running the SHIPPED arealight shader (intensity 10): Cl = I N.normalize(L) / (L.L). The renderer adds 1/(n p_A) and the",
                       "visibility only (Decision A), so the pixel is  I * integral cos_e cos_r / r^2 dA  of the closed form. n = 16 (the default).",
                       "Expected (probe_expected.py), the same on every hider and in .rslo and .slo:"] + pixel_comment(rows),
                      body("arealight", '"float intensity" [%g]' % pe.INTENSITY, EMITTER, "al_surface_matte"))
            for (i, j, e, s1, tol) in rows:
                add_probe("AreaLightProbe_QuadIrradiance-%s%s_x%dy%d" % (hider, sfx, i, j), name, i, j, tol, [e])
        # ---- the constant probe: no cosine and no 1/r^2 from the renderer (FR-012) --------------------------------------
        rows = []
        for (i, j) in pe.PIXELS:
            x, y = pe.pixel_center(i, j)
            e, s1 = pe.pixel_value("constant", pe.EMITTER, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.INTENSITY)
            rows.append((i, j, e, s1, pe.tolerance(s1, pe.SAMPLES)))
        name = "arealight-probe-constant-raytrace" + sfx
        add_scene(name, "raytrace", slo,
                  ["AreaLightProbe_ConstantCl: a light returning the constant Cl = intensity * lightcolor (al_light_constant, intensity 10).",
                   "Irradiance = the constant times the area-weighted receiver cosine: no emitter cosine and no 1/r^2 from the renderer.",
                   "Expected (probe_expected.py kind 'constant'):"] + pixel_comment(rows),
                  body("al_light_constant", '"float intensity" [%g]' % pe.INTENSITY, EMITTER, "al_surface_matte"))
        for (i, j, e, s1, tol) in rows:
            add_probe("AreaLightProbe_ConstantCl-raytrace%s_x%dy%d" % (sfx, i, j), name, i, j, tol, [e])
        # ---- the globals probes: what the light shader sees of the sampled point (US3 scenarios 1 and 3) ---------------
        quad = pe.Quad(*EMITTER_HI)
        A = quad.area
        cx = [sum(v[k] for v in EMITTER_HI) / 4.0 for k in range(3)]
        n_samples = pe.SAMPLES
        sd_y = A * (2.0 / math.sqrt(12.0)) / math.sqrt(n_samples) * 4.0     # 4 standard errors of A * mean(P_y) over the 2-wide quad
        sd_unit = A * (1.0 / math.sqrt(12.0)) / math.sqrt(n_samples) * 4.0  # of A * mean(u): u, v uniform over [0, 1]
        sd_st = A * (0.1 / math.sqrt(12.0)) / math.sqrt(n_samples) * 4.0    # of A * mean(s): s spans a 0.1 wide interval
        cases = [
            ("p", "al_light_p", poly(EMITTER_HI),
             "Cl = the light-surface P: the receiver sums A * mean(P_sample) = A * centroid = (12, 8, 8); x is exact (the quad is in x = 3), y and z carry sampling noise. The receiver's own P has x near 0, so a classic run reads about (0, ., 16).",
             [([0], 1e-3, [A * cx[0]]), ([1, 2], sd_y, [A * cx[1], A * cx[2]])]),
            ("n", "al_light_n", poly(EMITTER_HI),
             "Cl = (N + 1) / 2 of the light-surface N = (-1, 0, 0): the receiver sums A * (0, 0.5, 0.5) = (0, 2, 2) exactly (N is constant on the quad). The receiver's N = (0, 0, -1) gives (2, 2, 0) on a classic run.",
             [([0, 1, 2], 1e-4, [0.0, A * 0.5, A * 0.5])]),
            ("uv", "al_light_uv", poly(EMITTER_HI),
             "Cl = (u, v, 0) of the sampled point: A * mean(u, v) = (2, 2) with sampling noise; blue exactly 0. The receiver's own (u, v) at pixel (0, 0) is (0.0625, 0.0625 or 0.9375): far from 2.",
             [([0, 1], sd_unit, [A * 0.5, A * 0.5]), ([2], 1e-5, [0.0])]),
            ("st", "al_light_st",
             'Polygon "P" [%s] "varying float[2] st" [0.95 0.05  0.85 0.05  0.85 0.15  0.95 0.15]' % "  ".join("%g %g %g" % tuple(v) for v in EMITTER_HI),
             "Cl = (s, t, 0) with an explicit st that is mirrored and scaled: s = 0.95 - 0.1 u, t = 0.05 + 0.1 v (the per-vertex values follow the vertex order). The receiver sums A * (mean s, mean t) = A * (0.9, 0.1) = (3.6, 0.4) with small noise, blue 0. Default (u, v) would read (2, 2).",
             [([0, 1], sd_st, [A * 0.9, A * 0.1]), ([2], 1e-5, [0.0])]),
        ]
        for (kind, light, emitter_stmt, comment, probe_list) in cases:
            name = "arealight-probe-globals-%s-raytrace%s" % (kind, sfx)
            add_scene(name, "raytrace", slo,
                      ["AreaLightProbe_Globals (%s): the emitter (x = 3, y in [1, 3], z in [1, 3], facing -x, area 4) under %s;" % (kind, light),
                       "the receiver (al_surface_lightsum) sums Cl over the light's samples, each weighted by 1 / (n p_A) = A / n.",
                       comment,
                       "Probed at pixel (0, 0)."],
                      body(light, "", None, "al_surface_lightsum", emitter_extra=emitter_stmt))
            for (chs, tol, vals) in probe_list:
                add_probe("AreaLightProbe_Globals-%s-raytrace%s_x0y0_c%s" % (kind, sfx, "".join(str(c) for c in chs)), name, 0, 0, tol, vals, channels=chs)
        # ---- the receiver stays unchanged while the lights run (FR-011) -------------------------------------------------
        name = "arealight-probe-globals-check-raytrace" + sfx
        add_scene(name, "raytrace", slo,
                  ["AreaLightProbe_Globals (check): al_surface_check records P and N, runs diffuse() under the SHIPPED arealight (which writes",
                   "its own normal into N), and returns (|P - P0|, |N - N0|, 0). Both must be 0: the receiver's globals are untouched while any",
                   "light runs. A light that shares the receiver's N leaves a non-zero green channel on a classic run. Probed at pixel (3, 3)."],
                  body("arealight", '"float intensity" [%g]' % pe.INTENSITY, EMITTER, "al_surface_check"))
        add_probe("AreaLightProbe_Globals-check-raytrace%s_x3y3" % sfx, name, 3, 3, 1e-5, [0.0, 0.0, 0.0])
        # ---- the occluded probe: a flagged wall blocks, an unflagged twin does not (FR-017, FR-023) ----------------------
        rows_open = rows_q = []
        rows_q = []
        for (i, j) in pe.PIXELS:
            x, y = pe.pixel_center(i, j)
            e, s1 = pe.pixel_value("arealight", pe.EMITTER, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.INTENSITY)
            rows_q.append((i, j, e, s1, pe.tolerance(s1, pe.SAMPLES)))
        for wall, expect in (("flagged", None), ("unflagged", rows_q)):
            name = "arealight-probe-occluded-%s-raytrace%s" % (wall, sfx)
            add_scene(name, "raytrace", slo,
                      ["AreaLightProbe_Occluded (%s): the quad probe scene plus a wall at x = 1.5 (y in [-3, 3], z in [0, 5]) between the emitter and" % wall,
                       "every receiver pixel, outside the camera window." +
                       (" The wall carries Attribute \"visibility\" \"int transmission\" [1]: it casts the area light's shadow, every pixel reads 0." if wall == "flagged"
                        else " The wall is not flagged: an area light is not shadowed by it (FR-023), every pixel reads the unoccluded value:")] +
                      (pixel_comment(rows_q) if expect else []),
                      body("arealight", '"float intensity" [%g]' % pe.INTENSITY, EMITTER, "al_surface_matte", wall=wall))
            for (i, j, e, s1, tol) in rows_q:
                if wall == "flagged":
                    add_probe("AreaLightProbe_Occluded-flagged-raytrace%s_x%dy%d" % (sfx, i, j), name, i, j, 1e-6, [0.0])
                else:
                    add_probe("AreaLightProbe_Occluded-unflagged-raytrace%s_x%dy%d" % (sfx, i, j), name, i, j, tol, [e])
        # ---- the facing probes: nothing negative or non-finite (edge cases) ---------------------------------------------------
        add_scene("arealight-probe-facing-receiver-raytrace" + sfx, "raytrace", slo,
                  ["AreaLightProbe_Facing (receiver): the receiver al_surface_matte_n keeps N = +z (away from the emitter, no faceforward):",
                   "back-facing, so diffuse() is 0 for every sample. The estimator contributes 0, never a negative or non-finite value."],
                  body("arealight", '"float intensity" [%g]' % pe.INTENSITY, EMITTER, "al_surface_matte_n"))
        add_probe("AreaLightProbe_Facing-receiver-raytrace%s_x3y3" % sfx, "arealight-probe-facing-receiver-raytrace" + sfx, 3, 3, 1e-6, [0.0, 0.0, 0.0])
        add_scene("arealight-probe-facing-emitter-raytrace" + sfx, "raytrace", slo,
                  ["AreaLightProbe_Facing (emitter): the emitter's N is +x, the receivers are behind it: illuminate(P, N, PI/2) lights nothing.",
                   "The estimator contributes 0, never a negative or non-finite value."],
                  body("arealight", '"float intensity" [%g]' % pe.INTENSITY, EMITTER_BACK, "al_surface_matte"))
        add_probe("AreaLightProbe_Facing-emitter-raytrace%s_x3y3" % sfx, "arealight-probe-facing-emitter-raytrace" + sfx, 3, 3, 1e-6, [0.0, 0.0, 0.0])

        # ---- the controls (Phase 5; FR-018 to FR-020): Option / Attribute "arealight" ------------------------------------------
        def quad_rows(n):
            rows = []
            for (i, j) in pe.PIXELS:
                x, y = pe.pixel_center(i, j)
                e, s1 = pe.pixel_value("arealight", pe.EMITTER, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.INTENSITY)
                rows.append((i, j, e, s1, pe.tolerance(s1, n)))
            return rows

        def rows_comment(rows, n):
            return ["  pixel (%d, %d): expected %.9f, tolerance %.9f (4 sigma_1 / sqrt(%d), sigma_1 = %.9f)" % (i, j, e, tol, n, s1) for (i, j, e, s1, tol) in rows]

        full = [([], RECEIVER)]
        for tag, n, options in (("samples-4", 4, ['Option "arealight" "int samples" [4]']),
                                ("samples-64", 64, ['Option "arealight" "int samples" [64]'])):
            name = "arealight-controls-%s%s" % (tag, sfx)
            rows = quad_rows(n)
            add_scene(name, "raytrace", slo,
                      ["AreaLight_Controls_Render (%s): the quad probe scene with %s. The expected value does not depend on n; the tolerance" % (tag, options[0]),
                       "is 4 sigma_1 / sqrt(n), so the 64 sample image passes a tolerance 4 times tighter than the 4 sample one:"] + rows_comment(rows, n),
                      body_controls(options, [], full))
            for (i, j, e, s1, tol) in rows:
                add_probe("AreaLight_Controls_Render_%s%s_x%dy%d" % (tag, sfx, i, j), name, i, j, tol, [e])
        # mode off on one receiver of two: the left half (negative pixel-centre x) is dark, the right half reads its no-control value
        rows = quad_rows(pe.SAMPLES)
        name = "arealight-controls-off-receiver" + sfx
        add_scene(name, "raytrace", slo,
                  ["AreaLight_Controls_Render (off on one receiver): two receivers, the left one (x < 0) carries Attribute \"arealight\" \"string mode\" [\"off\"]:",
                   "its pixels are dark; the right one (x > 0) reads its no-control value (the default n = 16):"] + rows_comment(rows, pe.SAMPLES),
                  body_controls([], [], [(['Attribute "arealight" "string mode" ["off"]'], RECEIVER_LEFT), ([], RECEIVER_RIGHT)]))
        for (i, j, e, s1, tol) in rows:
            if pe.pixel_center(i, j)[0] < 0:
                add_probe("AreaLight_Controls_Render_off-receiver-dark%s_x%dy%d" % (sfx, i, j), name, i, j, 1e-6, [0.0])
            else:
                add_probe("AreaLight_Controls_Render_off-receiver-lit%s_x%dy%d" % (sfx, i, j), name, i, j, tol, [e])
        # off at the light level wins over a receiver that asks for full
        name = "arealight-controls-light-off-wins" + sfx
        add_scene(name, "raytrace", slo,
                  ["AreaLight_Controls_Render (off at the light level wins): the light's scope has mode off, the receiver asks for mode full:",
                   "off at any level turns the light off for that receiver: every pixel is dark."],
                  body_controls([], ['Attribute "arealight" "string mode" ["off"]'], [(['Attribute "arealight" "string mode" ["full"]'], RECEIVER)]))
        for (i, j) in pe.PIXELS:
            add_probe("AreaLight_Controls_Render_light-off-wins%s_x%dy%d" % (sfx, i, j), name, i, j, 1e-6, [0.0])
        # precedence and fast: scenes compared byte for byte with a twin (the draws depend on the resolved count only)
        add_scene("arealight-controls-precedence-object" + sfx, "raytrace", slo,
                  ["AreaLight_Controls_Render (object over light over scene): Option samples 4, the light's scope samples 8, the receiver samples 64:",
                   "the image is byte-identical to arealight-controls-samples-64 (Option samples 64)."],
                  body_controls(['Option "arealight" "int samples" [4]'], ['Attribute "arealight" "int samples" [8]'], [(['Attribute "arealight" "int samples" [64]'], RECEIVER)]))
        add_scene("arealight-controls-precedence-light" + sfx, "raytrace", slo,
                  ["AreaLight_Controls_Render (light over scene): Option samples 4, the light's scope samples 64, the receiver sets nothing:",
                   "the image is byte-identical to arealight-controls-samples-64."],
                  body_controls(['Option "arealight" "int samples" [4]'], ['Attribute "arealight" "int samples" [64]'], full))
        rows = quad_rows(4)
        name = "arealight-controls-fast-16" + sfx
        add_scene(name, "raytrace", slo,
                  ["AreaLight_Controls_Render (fast at n = 16): Option samples 16, mode fast: max(1, ceil(16 / 4)) = 4 samples, each with its occlusion ray.",
                   "The expected value is the full-mode one; the noise is that of 4 samples (tolerance 4 sigma_1 / sqrt(4)); the image is byte-identical to"
                   " arealight-controls-samples-4:"] + rows_comment(rows, 4),
                  body_controls(['Option "arealight" "int samples" [16] "string mode" ["fast"]'], [], full))
        for (i, j, e, s1, tol) in rows:
            add_probe("AreaLight_Controls_Render_fast-16%s_x%dy%d" % (sfx, i, j), name, i, j, tol, [e])
        add_scene("arealight-controls-fast-object" + sfx, "raytrace", slo,
                  ["AreaLight_Controls_Render (mode at the object level, samples at the scene level): Option samples 16, the receiver mode fast:",
                   "the two controls resolve independently; the image is byte-identical to arealight-controls-samples-4."],
                  body_controls(['Option "arealight" "int samples" [16]'], [], [(['Attribute "arealight" "string mode" ["fast"]'], RECEIVER)]))

    # ---- AreaLightBinding_Illuminate (FR-005): h 1, h 0, and the scene without any AreaLightSource -------------------------
    e, s1 = pe.pixel_value("arealight", pe.EMITTER, [pe.pixel_center(3, 3)[0], pe.pixel_center(3, 3)[1], pe.RECEIVER_Z], pe.RECEIVER_N, pe.INTENSITY)
    tol = pe.tolerance(s1, pe.SAMPLES)
    for variant, comment, kw in (
            ("on", "Illuminate 1 1 after the scope: the bound light lights the receiver: pixel (3, 3) = %.9f, tolerance %.9f." % (e, tol), dict()),
            ("off", "Illuminate 1 0 after the scope: the light is off, the receiver is dark (the no-light image).", dict(illuminate=False)),
            ("none", "No AreaLightSource at all: the same geometry and the same image as 'off' (a characterization guard).", dict(bind=False))):
        name = "arealight-illuminate-%s" % variant
        add_scene(name, "raytrace", False, ["AreaLightBinding_Illuminate (%s): %s" % (variant, comment)],
                  body("arealight", '"float intensity" [%g]' % pe.INTENSITY, EMITTER, "al_surface_matte", **kw))
    add_probe("AreaLightBinding_Illuminate_On_x3y3", "arealight-illuminate-on", 3, 3, tol, [e])

    # ---- the cmake file ------------------------------------------------------------------------------------------------------
    cm = ["# Spec 057 (area-light geometry), generated by specs/057-area-light-geometry/tools/gen_scenes.py: do not edit.",
          "# add_arealight_probe(<ctest name> <scene> <x> <y> <tolerance> [--channels=i,j] <value>...): one pixel of a float scene",
          "# (tests/visual/arealight-scenes.cmake defines the macro). Expected values and tolerances: probe_expected.py."]
    for (test, scene, x, y, tol, channels, values) in probes:
        args = ([channels and "--channels=" + ",".join(str(c) for c in channels)] if channels else []) + [fmt(v) for v in values]
        cm.append("add_arealight_probe(%s %s %d %d %s %s)" % (test, scene, x, y, fmt(tol), " ".join(args)))
    files[OUT_CMAKE] = "\n".join(cm) + "\n"

    changed = 0
    for path, text in sorted(files.items()):
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            changed += 1
            if not check:
                open(path, "w").write(text)
    print("%d files, %d %s" % (len(files), changed, "would change" if check else "written"))
    return 1 if (check and changed) else 0


