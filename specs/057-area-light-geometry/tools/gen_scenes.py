HIDERS = ["raytrace", "reyes", "zbuffer"]
OUT_RIB = os.path.join(ROOT, "examples", "rib", "tests")
OUT_CMAKE = os.path.join(ROOT, "tests", "visual", "arealight-probes.cmake")

files = {}      # path -> text
probes = []     # (test, scene, x, y, tol, channels or None, values)


def fmt(x):
    return repr(float(x))


def header(name, hider, slo, comment, size=8, float_out=True):
    lines = ["##RenderMan RIB-Structure 1.0", "# Spec 057 (area-light geometry), generated by specs/057-area-light-geometry/tools/gen_scenes.py: do not edit."]
    lines += ["# " + c if c else "#" for c in comment]
    lines.append("version 3.03")
    if slo:
        lines.append('Option "shaderformat" "default" ["slo"]')
    lines += [
        'Hider "%s" "jitter" [0]' % hider,
        "PixelSamples 1 1",
        'PixelFilter "box" 1 1',
    ]
    if float_out:
        lines.append('Quantize "rgba" 0 0 0 0')
    lines += [
        'Display "%s.tif" "file" "rgba"' % name,
        "Format %d %d 1" % (size, size),
        'Projection "orthographic"',
        "Clipping 0.1 100",
    ]
    return lines


def poly(p):
    return "Polygon \"P\" [%s]" % "  ".join("%g %g %g" % tuple(v) for v in p)


EMITTER = [[3, -1, 1], [3, -1, 3], [3, 1, 3], [3, 1, 1]]            # N = -x
EMITTER_BACK = [[3, -1, 1], [3, 1, 1], [3, 1, 3], [3, -1, 3]]       # N = +x (the receivers are behind it)
EMITTER_HI = [[3, 1, 1], [3, 1, 3], [3, 3, 3], [3, 3, 1]]           # N = -x, y in [1, 3]: every coordinate positive
RECEIVER = [[-1, -1, 4], [1, -1, 4], [1, 1, 4], [-1, 1, 4]]         # N = +z; the receiver shaders face it to the viewer or not
WALL = [[1.5, -3, 0], [1.5, -3, 5], [1.5, 3, 5], [1.5, 3, 0]]       # x = 1.5, between the emitter and every receiver pixel


def body(light, light_params, emitter, receiver_shader, wall=None, emitter_extra=None, illuminate=True, bind=True):
    b = ["WorldBegin", "  AttributeBegin"]
    if bind:
        b.append('    AreaLightSource "%s" 1 %s' % (light, light_params))
    b.append('    Surface "constant"')
    b.append("    " + (emitter_extra or poly(emitter)))
    b.append("  AttributeEnd")
    if bind and illuminate:
        b.append("  Illuminate 1 1")
    elif bind:
        b.append("  Illuminate 1 0")
    if wall is not None:
        b.append("  AttributeBegin")
        if wall == "flagged":
            b.append('    Attribute "visibility" "int transmission" [1]')
        b.append('    Surface "matte"')
        b.append("    " + poly(WALL))
        b.append("  AttributeEnd")
    b.append("  AttributeBegin")
    b.append('    Surface "%s"' % receiver_shader)
    b.append("    " + poly(RECEIVER))
    b.append("  AttributeEnd")
    b.append("WorldEnd")
    return b


RECEIVER_LEFT = [[-1, -1, 4], [0, -1, 4], [0, 1, 4], [-1, 1, 4]]     # x < 0: pixels with a negative pixel-centre x
RECEIVER_RIGHT = [[0, -1, 4], [1, -1, 4], [1, 1, 4], [0, 1, 4]]      # x > 0


def body_controls(options, light_attrs, receivers):
    """The controls scenes (Phase 5): the shipped arealight over the quad probe geometry. `options`: Option lines (before WorldBegin);
    `light_attrs`: Attribute lines inside the light's scope, before its AreaLightSource; `receivers`: [(attribute lines, polygon)],
    each its own al_surface_matte block."""
    b = list(options)
    b += ["WorldBegin", "  AttributeBegin"]
    b += ["    " + a for a in light_attrs]
    b.append('    AreaLightSource "arealight" 1 "float intensity" [%g]' % pe.INTENSITY)
    b.append('    Surface "constant"')
    b.append("    " + poly(EMITTER))
    b.append("  AttributeEnd")
    b.append("  Illuminate 1 1")
    for (attrs, polygon) in receivers:
        b.append("  AttributeBegin")
        b += ["    " + a for a in attrs]
        b.append('    Surface "al_surface_matte"')
        b.append("    " + poly(polygon))
        b.append("  AttributeEnd")
    b.append("WorldEnd")
    return b


def add_scene(name, hider, slo, comment, lines, size=8, float_out=True):
    if slo:
        # GitHub #126: a .slo surface whose only lighting call is illuminance(P) gathers no light. The light is the .slo under test, so
        # the receiver is pinned to .rslo (the #123 harness does the same)
        lines = [x for l in lines for x in (['    Attribute "shade" "shaderformat" ["rslo"]', l] if l == '    Surface "al_surface_lightsum"' else [l])]
    files[os.path.join(OUT_RIB, name + ".rib")] = "\n".join(header(name, hider, slo, comment, size, float_out) + lines) + "\n"


def add_probe(test, scene, x, y, tol, values, channels=None):
    probes.append((test, scene, x, y, tol, channels, values))


def pixel_comment(rows, n=16):
    out = []
    for (i, j, e, s1, tol) in rows:
        out.append("  pixel (%d, %d): expected %.9f, tolerance %.9f (4 sigma_1 / sqrt(%d), sigma_1 = %.9f)" % (i, j, e, tol, n, s1))
    return out


SOFT_Y = [-0.25, -0.05, 0.25]     # the mesh and subdivision emitters: a 2 x 2 grid of faces of unequal area covering the soft emitter
SOFT_Z = [1.75, 1.95, 2.25]


def soft_grid():
    p = []
    for z in SOFT_Z:
        for y in SOFT_Y:
            p.append("3 %g %g" % (y, z))
    verts = []
    for a in range(2):
        for b in range(2):
            verts += [a * 3 + b, (a + 1) * 3 + b, (a + 1) * 3 + b + 1, a * 3 + b + 1]
    return "  ".join(p), " ".join(str(v) for v in verts)


def soft_emitter(kind):
    if kind == "quad":
        return poly(pe.EMITTER_SOFT.vertices())
    pts, verts = soft_grid()
    if kind == "mesh":
        return 'PointsPolygons [4 4 4 4] [%s] "P" [%s]' % (verts, pts)
    # subdivision: the control mesh is flat and its boundary is interpolated, so the limit surface is the same rectangle
    return 'SubdivisionMesh "catmull-clark" [4 4 4 4] [%s] ["interpolateboundary"] [0 0] [] [] "P" [%s]' % (verts, pts)


def body_soft(kind, occluder="flagged", light_attrs=(), emitter_attrs=(), receiver_attrs=(), options=(), illuminate=True, emitter_stmt=None):
    """The soft-shadow family (Phase 6): the soft emitter under the shipped arealight (intensity 40, 64 samples at the light level), the
    sphere occluder `occluder` in {"flagged", "unflagged", "optout", None}, and the matte receiver z = 4."""
    b = list(options)
    b += ["WorldBegin", "  AttributeBegin", '    Attribute "arealight" "int samples" [%d]' % pe.SOFT_SAMPLES]
    b += ["    " + a for a in light_attrs]
    b.append('    AreaLightSource "arealight" 1 "float intensity" [%g]' % pe.INTENSITY_SOFT)
    b.append('    Surface "constant"')
    b += ["    " + a for a in emitter_attrs]
    b.append("    " + (emitter_stmt or soft_emitter(kind)))
    b.append("  AttributeEnd")
    if illuminate:
        b.append("  Illuminate 1 1")
    if occluder is not None:
        b.append("  AttributeBegin")
        if occluder == "flagged":
            b.append('    Attribute "visibility" "int transmission" [1]')
        elif occluder == "optout":
            b.append('    Attribute "visibility" "int transmission" [0]')
        b.append('    Surface "constant"')
        b.append("    Translate %g %g %g" % tuple(pe.OCCLUDER.c))
        b.append("    Sphere %g %g %g 360" % (pe.OCCLUDER.r, -pe.OCCLUDER.r, pe.OCCLUDER.r))
        b.append("  AttributeEnd")
    b.append("  AttributeBegin")
    b += ["    " + a for a in receiver_attrs]
    b.append('    Surface "al_surface_matte"')
    b.append("    " + poly(RECEIVER))
    b.append("  AttributeEnd")
    b.append("WorldEnd")
    return b


# The quadlight agreement (Phase 9, tasks.md T122): examples/rib/quadlight.rib's geometry and light, twice. OLD: the shipped quadlight shader
# (P0..P3, intensity 200, 16 samples). NEW: the same quad as geometry under AreaLightSource "arealight", intensity 200 / 4 (the quad's area,
# decision D-1: the shipped arealight returns I N.normalize(L) / (L.L) with no division by the area, the renderer scales by 1 / (n p_A)
# = A / n), 16 samples. Neither form shadows (D-1: quadlight's visibility() never occludes, GitHub #169; the sphere is unflagged, so the new
# form's shadow rays pass through it): the sphere and the disk are plain receivers in both. The model difference: quadlight.sl takes the
# cosine of the emitter at the quad's CENTRE (illuminate(center, N, PI/2) with L from the centre), the shipped arealight at each sample.
QUADLIGHT_P = [[3, 5, -2], [5, 5, -2], [3, 7, -2], [5, 7, -2]]   # quadlight's P0 P1 P2 P3
QUADLIGHT_I = 200
QUADLIGHT_AREA = 4.0


def quadlight_agreement_scene(form, slo, seed=None):
    name = "arealight-quadlight-agree-%s-raytrace%s" % (form, "-slo" if slo else "")
    p0, p1, p2, p3 = QUADLIGHT_P
    comment = [
        "AreaLight_QuadlightAgreement (US9, FR-022): examples/rib/quadlight.rib's geometry and light, the %s form. The OLD form is the shipped" % form.upper(),
        "quadlight shader; the NEW form is the same 2 x 2 quad as geometry under AreaLightSource \"arealight\" with the intensity divided by the",
        "quad's area (200 / 4 = 50: the shipped arealight returns I N.normalize(L) / (L.L) and the renderer adds A / n), 16 samples. Neither",
        "form shadows (quadlight's visibility() never occludes, GitHub #169; the sphere is not flagged transmission, so the new form's shadow",
        "rays pass through it): the sphere and the disk are plain receivers. Model difference: quadlight.sl takes the emitter cosine at the",
        "quad's CENTRE, the arealight at each sample point. The two renders are compared by the 8 x 8 block metric (the threshold is fixed after",
        "measurement, tasks.md T124).",
    ]
    lines = ["##RenderMan RIB-Structure 1.0", "# Spec 057 (area-light geometry), generated by specs/057-area-light-geometry/tools/gen_scenes.py: do not edit."]
    lines += ["# " + c for c in comment]
    lines += ["version 3.03"]
    if seed is not None:
        lines += ['Option "sampling" "seed" [%d]' % seed]
    lines += ['Hider "raytrace"', 'Display "%s.tif" "file" "rgba"' % name, 'Projection "perspective" "fov" 40', "Format 320 240 1", "Clipping 0.1 1000",
              "Translate 0 0 12", "WorldBegin"]
    if slo:
        lines += ['    Attribute "shade" "shaderformat" ["slo"]']
    if form == "old":
        lines += ['    LightSource "quadlight" 1 "P0" [%s] "P1" [%s]' % (" ".join(str(v) for v in p0), " ".join(str(v) for v in p1)),
                  '                "P2" [%s] "P3" [%s]' % (" ".join(str(v) for v in p2), " ".join(str(v) for v in p3)),
                  '                "intensity" [%d] "numSamples" [16]' % QUADLIGHT_I]
    else:
        # the polygon's vertex order p0 p1 p3 p2 gives the same normal as quadlight's (P1 - P0) x (P2 - P0): +z
        ring = [p0, p1, p3, p2]
        lines += ["    AttributeBegin", '        Attribute "arealight" "int samples" [16]',
                  '        AreaLightSource "arealight" 1 "float intensity" [%g]' % (QUADLIGHT_I / QUADLIGHT_AREA),
                  '        Surface "constant"', "        " + poly(ring), "    AttributeEnd", "    Illuminate 1 1"]
    lines += ["    AttributeBegin", "        Color [0.8 0.8 0.8]", '        Surface "matte"', "        Translate 0 0 3", "        Sphere 1.5 -1.5 1.5 360", "    AttributeEnd",
              "    AttributeBegin", "        Color [0.7 0.7 0.7]", '        Surface "matte"', "        Translate 0 -3 0", "        Rotate -90 1 0 0", "        Disk 0 20 360",
              "    AttributeEnd", "WorldEnd"]
    return name, "\n".join(lines) + "\n"


def quadlight_agreement_scenes():
    for slo in (False, True):
        for form in ("old", "new"):
            name, text = quadlight_agreement_scene(form, slo)
            files[os.path.join(OUT_RIB, name + ".rib")] = text


def main():
    check = "--check" in sys.argv
    pe.self_test()
    pe.quadric_self_test()
    for slo in (False, True):
        sfx = "-slo" if slo else ""
        # ---- the quad probe: shipped arealight, closed-form irradiance, three hiders ---------------------------------
        rows = []
        for (i, j) in pe.PIXELS:
            x, y = pe.pixel_center(i, j)
            e, s1 = pe.pixel_value("arealight", pe.EMITTER, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.INTENSITY)
            rows.append((i, j, e, s1, pe.tolerance(s1, pe.SAMPLES)))
        for hider in HIDERS:
            name = "arealight-probe-quad-%s%s" % (hider, sfx)
            add_scene(name, hider, slo,
                      ["AreaLightProbe_QuadIrradiance: a Lambertian plane (al_surface_matte, z = 4) under one quad (x = 3, facing -x, 2 x 2)",
                       "running the SHIPPED arealight shader (intensity 10): Cl = I N.normalize(L) / (L.L). The renderer adds 1/(n p_A) and the",
                       "visibility only (Decision A), so the pixel is  I * integral cos_e cos_r / r^2 dA  of the closed form. n = 16 (the default).",
                       "Expected (probe_expected.py), the same on every hider and in .rslo and .slo:"] + pixel_comment(rows),
                      body("arealight", '"float intensity" [%g]' % pe.INTENSITY, EMITTER, "al_surface_matte"))
            for (i, j, e, s1, tol) in rows:
                add_probe("AreaLightProbe_QuadIrradiance-%s%s_x%dy%d" % (hider, sfx, i, j), name, i, j, tol, [e])
        # ---- the constant probe: no cosine and no 1/r^2 from the renderer (FR-012) --------------------------------------
        rows = []
        for (i, j) in pe.PIXELS:
            x, y = pe.pixel_center(i, j)
            e, s1 = pe.pixel_value("constant", pe.EMITTER, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.INTENSITY)
            rows.append((i, j, e, s1, pe.tolerance(s1, pe.SAMPLES)))
        name = "arealight-probe-constant-raytrace" + sfx
        add_scene(name, "raytrace", slo,
                  ["AreaLightProbe_ConstantCl: a light returning the constant Cl = intensity * lightcolor (al_light_constant, intensity 10).",
                   "Irradiance = the constant times the area-weighted receiver cosine: no emitter cosine and no 1/r^2 from the renderer.",
                   "Expected (probe_expected.py kind 'constant'):"] + pixel_comment(rows),
                  body("al_light_constant", '"float intensity" [%g]' % pe.INTENSITY, EMITTER, "al_surface_matte"))
        for (i, j, e, s1, tol) in rows:
            add_probe("AreaLightProbe_ConstantCl-raytrace%s_x%dy%d" % (sfx, i, j), name, i, j, tol, [e])
        # ---- the quadric probes (Phase 7): a disk and a sphere under the shipped arealight (FR-009 P2, US6) -------------------
        for (kind, em, stmt, text) in (
                ("disk", pe.DISK, "Disk 0 1.2 360",
                 "a disk (radius 1.2, centre (3, 0, 2), in the plane z = 2 facing +z toward the receiver)"),
                ("sphere", pe.SPHERE, "Sphere 0.8 -0.8 0.8 360",
                 "a sphere (radius 0.8, centre (3, 0, 2); the points facing away from a receiver point are cut by the light's own illuminate cone)")):
            n_q = pe.quadric_samples(em, pe.PIXELS, rel=0.1)
            rows = []
            for (i, j) in pe.PIXELS:
                x, y = pe.pixel_center(i, j)
                e, s1 = pe.pixel_value_emitter(em, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.QUADRIC_INTENSITY)
                if kind == "sphere":
                    c = pe.sphere_closed_form(em.c, em.r, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.QUADRIC_INTENSITY)
                    assert abs(e - c) < 2e-3 * c      # the closed form E = I pi (r / d)^2 cos(theta_c) and the quadrature agree
                    e = c
                rows.append((i, j, e, s1, pe.tolerance(s1, n_q)))
            name = "arealight-probe-%s-raytrace%s" % (kind, sfx)
            comment = ["AreaLightProbe_%sIrradiance: a Lambertian plane (al_surface_matte, z = 4) under %s" % (kind.capitalize(), text),
                       "running the SHIPPED arealight shader (intensity 10) with %d samples (Attribute \"arealight\" \"int samples\"): the renderer adds" % n_q,
                       "1/(n p_A) and the visibility only (Decision A), so the pixel is  I * integral cos_e cos_r / r^2 dA.",
                       ("Closed form on the disk's axis: E = I pi R^2 / (R^2 + d^2); the probed pixels are off axis, so the expected values are the"
                        if kind == "disk" else
                        "Closed form: E = I pi (r / d)^2 cos(theta_c), theta_c the angle between the receiver normal and the direction to the centre (probe_expected.py).")]
            if kind == "disk":
                comment.append("polar quadrature of probe_expected.py (checked against the on-axis closed form by quadric_self_test()).")
            comment.append("Expected (probe_expected.py), the same in .rslo and .slo:")
            comment += pixel_comment(rows, n_q)
            lines = ["WorldBegin", "  AttributeBegin", '    Attribute "arealight" "int samples" [%d]' % n_q,
                     '    AreaLightSource "arealight" 1 "float intensity" [%g]' % pe.QUADRIC_INTENSITY,
                     '    Surface "constant"', "    Translate 3 0 2", "    " + stmt, "  AttributeEnd", "  Illuminate 1 1",
                     "  AttributeBegin", '    Surface "al_surface_matte"', "    " + poly(RECEIVER), "  AttributeEnd", "WorldEnd"]
            add_scene(name, "raytrace", slo, comment, lines)
            for (i, j, e, s1, tol) in rows:
                add_probe("AreaLightProbe_%sIrradiance-raytrace%s_x%dy%d" % (kind.capitalize(), sfx, i, j), name, i, j, tol, [e])
        # ---- the blobby probe (Phase 11): a blobby emits through the polygon mesh RiBlobby derives (the maintainer's correction of FR-009's out-of-scope list) --
        # The surface of a unit ellipsoid blobby (opcode 1001) is at the field value 0.4 of f = (1 - r^2)^3 (BLOBBY_SURFACES.md: "The surface threshold is derived"):
        # r = sqrt(1 - 0.4^(1/3)) = 0.5130241; a matrix scale of 1.5 makes it 0.7695362, measured on a silhouette render at 0.52 for scale 1 and 0.62 for 1.2
        # (one pixel of 0.02). The expected values are the sphere's (a derived mesh is the sphere inscribed in facets: a deficit allowed for below).
        r_blobby = math.sqrt(1.0 - 0.4 ** (1.0 / 3.0)) * 1.5
        bl_em = pe.SphereEmitter([3.0, 0.0, 2.0], r_blobby)
        n_b = pe.quadric_samples(bl_em, pe.PIXELS, rel=0.1)
        rows = []
        for (i, j) in pe.PIXELS:
            x, y = pe.pixel_center(i, j)
            e, s1 = pe.pixel_value_emitter(bl_em, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.QUADRIC_INTENSITY)
            c = pe.sphere_closed_form(bl_em.c, bl_em.r, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.QUADRIC_INTENSITY)
            assert abs(e - c) < 2e-3 * c
            rows.append((i, j, c, s1, pe.tolerance(s1, n_b) + 0.03 * c))
        name = "arealight-probe-blobby-raytrace" + sfx
        comment = ["AreaLightProbe_BlobbyIrradiance: a blobby (one ellipsoid field, matrix scale 1.5: surface radius %.7f, centre (3, 0, 2)) as the emitter under the" % r_blobby,
                   "shipped arealight (intensity 10), %d samples. RiBlobby derives a polygon mesh and hands it to addObject, so the blobby emits through that mesh." % n_b,
                   "Expected: the closed form of a sphere of that radius, E = I pi (r / d)^2 cos(theta_c), the tolerance 4 sigma_1 / sqrt(n) plus 3 % of E for the",
                   "facets of the derived mesh (pre-declared; a blobby that did not emit reads 0). Expected (probe_expected.py):"] + pixel_comment(rows, n_b)
        lines = ["WorldBegin", "  AttributeBegin", '    Attribute "arealight" "int samples" [%d]' % n_b,
                 '    AreaLightSource "arealight" 1 "float intensity" [%g]' % pe.QUADRIC_INTENSITY,
                 '    Surface "constant"', "    Translate 3 0 2", '    Blobby 1 [1001 0] [1.5 0 0 0  0 1.5 0 0  0 0 1.5 0  0 0 0 1] [""]', "  AttributeEnd", "  Illuminate 1 1",
                 "  AttributeBegin", '    Surface "al_surface_matte"', "    " + poly(RECEIVER), "  AttributeEnd", "WorldEnd"]
        add_scene(name, "raytrace", slo, comment, lines)
        for (i, j, e, s1, tol) in rows:
            add_probe("AreaLightProbe_BlobbyIrradiance-raytrace%s_x%dy%d" % (sfx, i, j), name, i, j, tol, [e])
        # ---- the patch probe (Phase 10): the quad probe's emitter as a bilinear patch (FR-009 P3, US7) -------------------------
        rows = []
        for (i, j) in pe.PIXELS:
            x, y = pe.pixel_center(i, j)
            e, s1 = pe.pixel_value("arealight", pe.EMITTER, [x, y, pe.RECEIVER_Z], pe.RECEIVER_N, pe.INTENSITY)
            rows.append((i, j, e, s1, pe.tolerance(s1, pe.SAMPLES)))
        e0, e1, e2, e3 = pe.EMITTER.vertices()          # the polygon ring p0 p1 p2 p3 (normal -x): a patch lists P00 P10 P01 P11 = p0 p1 p3 p2
        patch_stmt = 'Patch "bilinear" "P" [%s]' % "  ".join("%g %g %g" % tuple(v) for v in (e0, e1, e3, e2))
        name = "arealight-probe-patch-raytrace" + sfx
        add_scene(name, "raytrace", slo,
                  ["AreaLightProbe_PatchIrradiance: the quad probe (a Lambertian plane z = 4 under a 2 x 2 emitter in x = 3 facing -x, the shipped arealight,",
                   "intensity 10, n = 16) with the emitter written as RiPatch \"bilinear\" instead of a polygon: P00 P10 P01 P11 = the polygon's p0 p1 p3 p2, so",
                   "dPdu x dPdv is -x as the polygon's normal is. Planar, so the exact quad sampler; the closed form is the quad's. Expected (probe_expected.py):"] + pixel_comment(rows),
                  body("arealight", '"float intensity" [%g]' % pe.INTENSITY, pe.EMITTER, "al_surface_matte", emitter_extra=patch_stmt))
        for (i, j, e, s1, tol) in rows:
            add_probe("AreaLightProbe_PatchIrradiance-raytrace%s_x%dy%d" % (sfx, i, j), name, i, j, tol, [e])
