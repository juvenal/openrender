#!/usr/bin/env python3
"""Spec 057 scene generator (tasks.md T060): the closed-form probe scenes of the area-light geometry spec.

Writes examples/rib/tests/arealight-{probe,illuminate}-*.rib and tests/visual/arealight-probes.cmake (one
add_arealight_probe() call per probed pixel; the expected values and tolerances come from probe_expected.py, the same
numbers the RIBs are built from). The generated files are checked in (CLAUDE.md gotcha 21): a regeneration is diffed.

    python3 -I specs/057-area-light-geometry/tools/gen_scenes.py [--check]

--check writes nothing and exits 1 if a file would change.

Geometry (camera space, an orthographic camera at the origin looking along +z, `Format 8 8 1`, window [-1, 1]^2):
  receiver  the plane z = 4 spanning exactly the window, seen from the camera (so receiver u, v run over [0, 1] across
            the image: pixel (0, 0) has u = 0.0625)
  emitter   a quad in the plane x = 3, facing -x, outside the window: p0 (3,-1,1) p1 (3,-1,3) p2 (3,1,3) p3 (3,1,1), area 4
            (the globals probes use the same shape moved to y in [1, 3] so every coordinate is positive)
  light     AreaLightSource "<light>" 1 ... in an attribute block with the emitter, then `Illuminate 1 1` for the receiver
The scenes run on the default area-light sample count (16): Option "arealight" arrives with the controls (Phase 5).
"""
