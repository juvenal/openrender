def fmt(x):
    return repr(float(x))


def header(name, hider, slo, comment, size=8, float_out=True):
    lines = ["##RenderMan RIB-Structure 1.0", "# Spec 057 (area-light geometry), generated by specs/057-area-light-geometry/tools/gen_scenes.py: do not edit."]
    lines += ["# " + c if c else "#" for c in comment]
    lines.append("version 3.03")
    if slo:
        lines.append('Option "shaderformat" "default" ["slo"]')
    lines += [
        'Hider "%s" "jitter" [0]' % hider,
        "PixelSamples 1 1",
        'PixelFilter "box" 1 1',
    ]
    if float_out:
        lines.append('Quantize "rgba" 0 0 0 0')
    lines += [
        'Display "%s.tif" "file" "rgba"' % name,
        "Format %d %d 1" % (size, size),
        'Projection "orthographic"',
        "Clipping 0.1 100",
    ]
    return lines


def poly(p):
    return "Polygon \"P\" [%s]" % "  ".join("%g %g %g" % tuple(v) for v in p)


EMITTER = [[3, -1, 1], [3, -1, 3], [3, 1, 3], [3, 1, 1]]            # N = -x
EMITTER_BACK = [[3, -1, 1], [3, 1, 1], [3, 1, 3], [3, -1, 3]]       # N = +x (the receivers are behind it)
EMITTER_HI = [[3, 1, 1], [3, 1, 3], [3, 3, 3], [3, 3, 1]]           # N = -x, y in [1, 3]: every coordinate positive
RECEIVER = [[-1, -1, 4], [1, -1, 4], [1, 1, 4], [-1, 1, 4]]         # N = +z; the receiver shaders face it to the viewer or not
WALL = [[1.5, -3, 0], [1.5, -3, 5], [1.5, 3, 5], [1.5, 3, 0]]       # x = 1.5, between the emitter and every receiver pixel


def body(light, light_params, emitter, receiver_shader, wall=None, emitter_extra=None, illuminate=True, bind=True):
    b = ["WorldBegin", "  AttributeBegin"]
    if bind:
        b.append('    AreaLightSource "%s" 1 %s' % (light, light_params))
    b.append('    Surface "constant"')
    b.append("    " + (emitter_extra or poly(emitter)))
    b.append("  AttributeEnd")
    if bind and illuminate:
        b.append("  Illuminate 1 1")
    elif bind:
        b.append("  Illuminate 1 0")
    if wall is not None:
        b.append("  AttributeBegin")
        if wall == "flagged":
            b.append('    Attribute "visibility" "int transmission" [1]')
        b.append('    Surface "matte"')
        b.append("    " + poly(WALL))
        b.append("  AttributeEnd")
    b.append("  AttributeBegin")
    b.append('    Surface "%s"' % receiver_shader)
    b.append("    " + poly(RECEIVER))
    b.append("  AttributeEnd")
    b.append("WorldEnd")
    return b


RECEIVER_LEFT = [[-1, -1, 4], [0, -1, 4], [0, 1, 4], [-1, 1, 4]]     # x < 0: pixels with a negative pixel-centre x
RECEIVER_RIGHT = [[0, -1, 4], [1, -1, 4], [1, 1, 4], [0, 1, 4]]      # x > 0


def body_controls(options, light_attrs, receivers):
    """The controls scenes (Phase 5): the shipped arealight over the quad probe geometry. `options`: Option lines (before WorldBegin);
    `light_attrs`: Attribute lines inside the light's scope, before its AreaLightSource; `receivers`: [(attribute lines, polygon)],
    each its own al_surface_matte block."""
    b = list(options)
    b += ["WorldBegin", "  AttributeBegin"]
    b += ["    " + a for a in light_attrs]
    b.append('    AreaLightSource "arealight" 1 "float intensity" [%g]' % pe.INTENSITY)
    b.append('    Surface "constant"')
    b.append("    " + poly(EMITTER))
    b.append("  AttributeEnd")
    b.append("  Illuminate 1 1")
    for (attrs, polygon) in receivers:
        b.append("  AttributeBegin")
        b += ["    " + a for a in attrs]
        b.append('    Surface "al_surface_matte"')
        b.append("    " + poly(polygon))
        b.append("  AttributeEnd")
    b.append("WorldEnd")
    return b


def add_scene(name, hider, slo, comment, lines, size=8, float_out=True):
    if slo:
        # GitHub #126: a .slo surface whose only lighting call is illuminance(P) gathers no light. The light is the .slo under test, so
        # the receiver is pinned to .rslo (the #123 harness does the same)
        lines = [x for l in lines for x in (['    Attribute "shade" "shaderformat" ["rslo"]', l] if l == '    Surface "al_surface_lightsum"' else [l])]
    files[os.path.join(OUT_RIB, name + ".rib")] = "\n".join(header(name, hider, slo, comment, size, float_out) + lines) + "\n"


def add_probe(test, scene, x, y, tol, values, channels=None):
    probes.append((test, scene, x, y, tol, channels, values))


def pixel_comment(rows, n=16):
    out = []
    for (i, j, e, s1, tol) in rows:
        out.append("  pixel (%d, %d): expected %.9f, tolerance %.9f (4 sigma_1 / sqrt(%d), sigma_1 = %.9f)" % (i, j, e, tol, n, s1))
    return out


SOFT_Y = [-0.25, -0.05, 0.25]     # the mesh and subdivision emitters: a 2 x 2 grid of faces of unequal area covering the soft emitter
SOFT_Z = [1.75, 1.95, 2.25]


def soft_grid():
    p = []
    for z in SOFT_Z:
        for y in SOFT_Y:
            p.append("3 %g %g" % (y, z))
    verts = []
    for a in range(2):
        for b in range(2):
            verts += [a * 3 + b, (a + 1) * 3 + b, (a + 1) * 3 + b + 1, a * 3 + b + 1]
    return "  ".join(p), " ".join(str(v) for v in verts)


def soft_emitter(kind):
    if kind == "quad":
        return poly(pe.EMITTER_SOFT.vertices())
    pts, verts = soft_grid()
    if kind == "mesh":
        return 'PointsPolygons [4 4 4 4] [%s] "P" [%s]' % (verts, pts)
    # subdivision: the control mesh is flat and its boundary is interpolated, so the limit surface is the same rectangle
    return 'SubdivisionMesh "catmull-clark" [4 4 4 4] [%s] ["interpolateboundary"] [0 0] [] [] "P" [%s]' % (verts, pts)


def body_soft(kind, occluder="flagged", light_attrs=(), emitter_attrs=(), receiver_attrs=(), options=(), illuminate=True, emitter_stmt=None):
    """The soft-shadow family (Phase 6): the soft emitter under the shipped arealight (intensity 40, 64 samples at the light level), the
    sphere occluder `occluder` in {"flagged", "unflagged", "optout", None}, and the matte receiver z = 4."""
    b = list(options)
    b += ["WorldBegin", "  AttributeBegin", '    Attribute "arealight" "int samples" [%d]' % pe.SOFT_SAMPLES]
    b += ["    " + a for a in light_attrs]
    b.append('    AreaLightSource "arealight" 1 "float intensity" [%g]' % pe.INTENSITY_SOFT)
    b.append('    Surface "constant"')
    b += ["    " + a for a in emitter_attrs]
    b.append("    " + (emitter_stmt or soft_emitter(kind)))
    b.append("  AttributeEnd")
    if illuminate:
        b.append("  Illuminate 1 1")
    if occluder is not None:
        b.append("  AttributeBegin")
        if occluder == "flagged":
            b.append('    Attribute "visibility" "int transmission" [1]')
        elif occluder == "optout":
            b.append('    Attribute "visibility" "int transmission" [0]')
        b.append('    Surface "constant"')
        b.append("    Translate %g %g %g" % tuple(pe.OCCLUDER.c))
        b.append("    Sphere %g %g %g 360" % (pe.OCCLUDER.r, -pe.OCCLUDER.r, pe.OCCLUDER.r))
        b.append("  AttributeEnd")
    b.append("  AttributeBegin")
    b += ["    " + a for a in receiver_attrs]
    b.append('    Surface "al_surface_matte"')
    b.append("    " + poly(RECEIVER))
    b.append("  AttributeEnd")
    b.append("WorldEnd")
    return b


# The quadlight agreement (Phase 9, tasks.md T122): examples/rib/quadlight.rib's geometry and light, twice. OLD: the shipped quadlight shader
# (P0..P3, intensity 200, 16 samples). NEW: the same quad as geometry under AreaLightSource "arealight", intensity 200 / 4 (the quad's area,
# decision D-1: the shipped arealight returns I N.normalize(L) / (L.L) with no division by the area, the renderer scales by 1 / (n p_A)
# = A / n), 16 samples. Neither form shadows (D-1: quadlight's visibility() never occludes, GitHub #169; the sphere is unflagged, so the new
# form's shadow rays pass through it): the sphere and the disk are plain receivers in both. The model difference: quadlight.sl takes the
# cosine of the emitter at the quad's CENTRE (illuminate(center, N, PI/2) with L from the centre), the shipped arealight at each sample.
QUADLIGHT_P = [[3, 5, -2], [5, 5, -2], [3, 7, -2], [5, 7, -2]]   # quadlight's P0 P1 P2 P3
QUADLIGHT_I = 200
QUADLIGHT_AREA = 4.0


def quadlight_agreement_scene(form, slo, seed=None):
    name = "arealight-quadlight-agree-%s-raytrace%s" % (form, "-slo" if slo else "")
    p0, p1, p2, p3 = QUADLIGHT_P
    comment = [
        "AreaLight_QuadlightAgreement (US9, FR-022): examples/rib/quadlight.rib's geometry and light, the %s form. The OLD form is the shipped" % form.upper(),
        "quadlight shader; the NEW form is the same 2 x 2 quad as geometry under AreaLightSource \"arealight\" with the intensity divided by the",
        "quad's area (200 / 4 = 50: the shipped arealight returns I N.normalize(L) / (L.L) and the renderer adds A / n), 16 samples. Neither",
        "form shadows (quadlight's visibility() never occludes, GitHub #169; the sphere is not flagged transmission, so the new form's shadow",
        "rays pass through it): the sphere and the disk are plain receivers. Model difference: quadlight.sl takes the emitter cosine at the",
        "quad's CENTRE, the arealight at each sample point. The two renders are compared by the 8 x 8 block metric (the threshold is fixed after",
        "measurement, tasks.md T124).",
    ]
    lines = ["##RenderMan RIB-Structure 1.0", "# Spec 057 (area-light geometry), generated by specs/057-area-light-geometry/tools/gen_scenes.py: do not edit."]
    lines += ["# " + c for c in comment]
    lines += ["version 3.03"]
    if seed is not None:
        lines += ['Option "sampling" "seed" [%d]' % seed]
    lines += ['Hider "raytrace"', 'Display "%s.tif" "file" "rgba"' % name, 'Projection "perspective" "fov" 40', "Format 320 240 1", "Clipping 0.1 1000",
              "Translate 0 0 12", "WorldBegin"]
    if slo:
        lines += ['    Attribute "shade" "shaderformat" ["slo"]']
    if form == "old":
        lines += ['    LightSource "quadlight" 1 "P0" [%s] "P1" [%s]' % (" ".join(str(v) for v in p0), " ".join(str(v) for v in p1)),
                  '                "P2" [%s] "P3" [%s]' % (" ".join(str(v) for v in p2), " ".join(str(v) for v in p3)),
                  '                "intensity" [%d] "numSamples" [16]' % QUADLIGHT_I]
    else:
        # the polygon's vertex order p0 p1 p3 p2 gives the same normal as quadlight's (P1 - P0) x (P2 - P0): +z
        ring = [p0, p1, p3, p2]
        lines += ["    AttributeBegin", '        Attribute "arealight" "int samples" [16]',
                  '        AreaLightSource "arealight" 1 "float intensity" [%g]' % (QUADLIGHT_I / QUADLIGHT_AREA),
                  '        Surface "constant"', "        " + poly(ring), "    AttributeEnd", "    Illuminate 1 1"]
    lines += ["    AttributeBegin", "        Color [0.8 0.8 0.8]", '        Surface "matte"', "        Translate 0 0 3", "        Sphere 1.5 -1.5 1.5 360", "    AttributeEnd",
              "    AttributeBegin", "        Color [0.7 0.7 0.7]", '        Surface "matte"', "        Translate 0 -3 0", "        Rotate -90 1 0 0", "        Disk 0 20 360",
              "    AttributeEnd", "WorldEnd"]
    return name, "\n".join(lines) + "\n"


