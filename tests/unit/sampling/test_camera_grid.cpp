// Sampling_CameraGridConsistency (research R3.1).
//
// The reyes and raytrace hiders both generate a margin of subpixel samples
// around each bucket, in different units. This test runs both formulas over a
// 3 x 3 grid of buckets with margins and asserts that they give equal
// SampleIds, and that a margin sample shared by neighbouring buckets gets the
// same SampleId (and so the same key) in every bucket.
#include <map>

#include "sampling_test_util.h"

using namespace sptest;

namespace {

constexpr int kNx = 3, kNy = 3;
constexpr int kXOff = 2, kYOff = 2;   // xSampleOffset, ySampleOffset (margin, in subpixels)
constexpr int kBucket = 4;            // bucket size in pixels
constexpr int kBuckets = 3;           // buckets per axis
constexpr uint32_t kFrame = 4, kSeed = 0xFFFFFFF1u;  // a negative seed as int32

sp::SampleId makeId(int32_t absSubX, int32_t absSubY) {
    sp::SampleId id;
    id.px = sp::floorDiv(absSubX, kNx);
    id.py = sp::floorDiv(absSubY, kNy);
    id.sampleIndex = static_cast<uint32_t>(sp::floorMod(absSubY, kNy) * kNx + sp::floorMod(absSubX, kNx));
    id.frame = kFrame;
    id.seed = kSeed;
    return id;
}

// The same arithmetic with no floor helpers: shift into the positive range
// first so that truncating division is correct.
sp::SampleId expectedId(int32_t absSubX, int32_t absSubY) {
    constexpr int kShiftPixels = 1000;
    const int32_t sx = absSubX + kShiftPixels * kNx, sy = absSubY + kShiftPixels * kNy;
    sp::SampleId id;
    id.px = sx / kNx - kShiftPixels;
    id.py = sy / kNy - kShiftPixels;
    id.sampleIndex = static_cast<uint32_t>((sy % kNy) * kNx + (sx % kNx));
    id.frame = kFrame;
    id.seed = kSeed;
    return id;
}

bool sameId(const sp::SampleId &a, const sp::SampleId &b) {
    return a.px == b.px && a.py == b.py && a.sampleIndex == b.sampleIndex && a.frame == b.frame && a.seed == b.seed;
}

void floorHelpers() {
    SP_CHECK(sp::floorDiv(-1, 3) == -1);
    SP_CHECK(sp::floorDiv(-3, 3) == -1);
    SP_CHECK(sp::floorDiv(-4, 3) == -2);
    SP_CHECK(sp::floorDiv(0, 3) == 0);
    SP_CHECK(sp::floorDiv(5, 3) == 1);
    SP_CHECK(sp::floorMod(-1, 3) == 2);
    SP_CHECK(sp::floorMod(-3, 3) == 0);
    SP_CHECK(sp::floorMod(-4, 3) == 2);
    SP_CHECK(sp::floorMod(5, 3) == 2);
}

void cameraGridConsistency() {
    floorHelpers();

    const int width = kBucket * kNx + 2 * kXOff;   // subpixels across one bucket with margins
    const int height = kBucket * kNy + 2 * kYOff;
    std::map<std::pair<int, int>, sp::SampleId> byAbs;    // absSub -> SampleId, first seen
    std::map<std::pair<int, int>, uint64_t> keyByAbs;
    int negative = 0, shared = 0;

    for (int by = 0; by < kBuckets; ++by)
        for (int bx = 0; bx < kBuckets; ++bx) {
            const int pixelLeft = bx * kBucket, pixelTop = by * kBucket;
            const int subLeft = pixelLeft * kNx - kXOff;  // reyes: left/top are in subpixels
            const int subTop = pixelTop * kNy - kYOff;
            for (int i = 0; i < height; ++i)
                for (int j = 0; j < width; ++j) {
                    // Reyes: absSub = left + j (left in subpixel units).
                    const int reyesX = subLeft + j, reyesY = subTop + i;
                    // Raytrace: absSub = left*nx - xSampleOffset + col (left in pixels).
                    const int rayX = pixelLeft * kNx - kXOff + j, rayY = pixelTop * kNy - kYOff + i;
                    const sp::SampleId r = makeId(reyesX, reyesY);
                    const sp::SampleId t = makeId(rayX, rayY);
                    SP_CHECK(sameId(r, t));
                    SP_CHECK(sameId(r, expectedId(reyesX, reyesY)));
                    SP_CHECK(r.sampleIndex < static_cast<uint32_t>(kNx * kNy));
                    if (reyesX < 0 || reyesY < 0) ++negative;

                    const auto abs = std::make_pair(reyesX, reyesY);
                    const uint64_t key = sp::cameraKey(r).full;
                    auto it = byAbs.find(abs);
                    if (it == byAbs.end()) {
                        byAbs[abs] = r;
                        keyByAbs[abs] = key;
                    } else {  // a margin sample regenerated by a neighbouring bucket
                        ++shared;
                        SP_CHECK(sameId(it->second, r));
                        SP_CHECK(keyByAbs[abs] == key);
                    }
                }
        }

    SP_CHECK(negative > 0);  // the border margin reaches negative coordinates
    SP_CHECK(shared > 0);    // neighbouring buckets do overlap

    // Distinct subpixels never share a key.
    std::map<uint64_t, std::pair<int, int>> owner;
    for (const auto &e : keyByAbs) {
        auto ins = owner.insert({e.second, e.first});
        SP_CHECK(ins.second);
    }
    std::printf("%zu subpixels, %d negative-coordinate samples, %d margin samples shared between buckets\n",
                byAbs.size(), negative, shared);
}

}  // namespace

int main(int argc, char **argv) {
    return runCase(argc, argv, {{"camera_grid", cameraGridConsistency}});
}
