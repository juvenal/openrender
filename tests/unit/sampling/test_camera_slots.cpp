// Sampling_CameraSlotsEqual (research R3.1, T057).
//
// Under the Sobol, PMJ02 and Independent backends the reyes and raytrace
// hiders take film, lens, time and importance from the same camera slots,
// indexed by the absolute subpixel coordinates. The hiders count their bucket
// origin in different units (reyes in subpixels, raytrace in pixels), so each
// converts its own loop index through a CSampler helper and both then call
// CSampler::cameraSample(). This test drives those two paths over a grid of
// buckets with margins and checks, for every subpixel:
//
//   1. the two paths give bit-identical values (jitter, time stratum, importance,
//      lens point and camera key), and a margin sample regenerated by a
//      neighbouring bucket gives the same values again;
//   2. the values are the ones the camera slots define: the jitter mapping
//      jitter * (u - 0.5) + 0.5001011 with u from the slots, the time stratum
//      (row * nx + column), the transposed importance stratum (column * ny + row),
//      and the camera key of the absolute SampleId. The expected values are
//      computed here from common/sampling.h alone, never through CSampler;
//   3. the lens point is the lens slot through sampleDisk() (when the first
//      attempt of the rejection loop falls in the disk it is that point, and the
//      point is always inside the disk), and is exactly 0 when no lens is wanted.
//
// It also checks the unit conversions themselves, which are plain arithmetic.
#include <map>
#include <set>

#include "sampler.h"
#include "sampling_test_util.h"

using namespace sptest;

namespace {

constexpr int kBucket = 4;   // pixels per bucket side
constexpr int kBuckets = 3;  // buckets per axis
constexpr uint32_t kFrame = 4, kSeed = 0xFFFFFFF1u;  // a negative seed as int32

struct Grid {
    int nx, ny, xOff, yOff;
};
constexpr Grid kGrids[] = {{3, 3, 2, 2}, {4, 2, 2, 1}};
constexpr float kJitters[] = {0.0f, 0.37f, 1.0f};

bool sameBits(float a, float b) { return bitsOf(a) == bitsOf(b); }
bool close(float a, float b) { return std::fabs(a - b) <= 2e-6f; }

bool sameValue(const CSampleValue &a, const CSampleValue &b) {
    return sameBits(a.jitterX, b.jitterX) && sameBits(a.jitterY, b.jitterY) && sameBits(a.timeStratum, b.timeStratum) &&
           sameBits(a.importance, b.importance) && sameBits(a.lensU, b.lensU) && sameBits(a.lensV, b.lensV) &&
           a.key.full == b.key.full && a.key.path == b.key.path && a.key.pixelSampleIndex == b.key.pixelSampleIndex &&
           a.key.kind == b.key.kind;
}

void unitConversions() {
    // Reyes: left/top are already subpixels.
    SP_CHECK(CSampler::reyesAbsSub(-4, 0) == -4);
    SP_CHECK(CSampler::reyesAbsSub(-4, 7) == 3);
    SP_CHECK(CSampler::reyesAbsSub(12, 5) == 17);
    // Raytrace: left/top are pixels: first subpixel = left * samples - offset.
    SP_CHECK(CSampler::raytraceAbsSub(0, 3, 2, 0) == -2);
    SP_CHECK(CSampler::raytraceAbsSub(4, 3, 2, 0) == 10);
    SP_CHECK(CSampler::raytraceAbsSub(4, 3, 2, 5) == 15);
    SP_CHECK(CSampler::raytraceAbsSub(2, 2, 1, 3) == 6);
    // The same subpixel from both units.
    SP_CHECK(CSampler::reyesAbsSub(4 * 3 - 2, 5) == CSampler::raytraceAbsSub(4, 3, 2, 5));
}

// The values the slots define for the subpixel (absX, absY).
struct Expected {
    sp::SampleId id;
    float jitterX, jitterY, time, importance;
    sp::Sample2D lens;
};

Expected expectedFor(const sp::CSamplingConfig &cfg, int absX, int absY) {
    Expected e;
    e.id.px = sp::floorDiv(absX, cfg.nx);
    e.id.py = sp::floorDiv(absY, cfg.ny);
    const int col = sp::floorMod(absX, cfg.nx), row = sp::floorMod(absY, cfg.ny);
    e.id.sampleIndex = static_cast<uint32_t>(row * cfg.nx + col);
    e.id.frame = cfg.frame;
    e.id.seed = cfg.seed;
    const float k = CSampler::kJitterConstant, total = static_cast<float>(cfg.nx * cfg.ny);
    const sp::Sample2D film = sp::cameraFilm(cfg, e.id);
    e.jitterX = cfg.jitter * (film.u - 0.5f) + k;
    e.jitterY = cfg.jitter * (film.v - 0.5f) + k;
    e.time = (static_cast<float>(row * cfg.nx + col) + cfg.jitter * (sp::cameraTime(cfg, e.id) - 0.5f) + k) / total;
    e.importance = 1.0f - (static_cast<float>(col * cfg.ny + row) + cfg.jitter * (sp::cameraImportance(cfg, e.id) - 0.5f) + k) / total;
    e.lens = sp::cameraLens(cfg, e.id);
    return e;
}

void cameraSlotsEqual() {
    unitConversions();

    int checked = 0, shared = 0, negative = 0, rejectedFirst = 0, acceptedFirst = 0;
    for (const sp::Backend backend : kBackends)
        for (const Grid &g : kGrids)
            for (const float jitter : kJitters)
                for (const bool wantLens : {false, true}) {
                    sp::CSamplingConfig cfg{};
                    cfg.backend = backend;
                    cfg.seed = kSeed;
                    cfg.frame = kFrame;
                    cfg.nx = g.nx;
                    cfg.ny = g.ny;
                    cfg.jitter = jitter;

                    const int width = kBucket * g.nx + 2 * g.xOff;  // subpixels across a bucket, margins included
                    const int height = kBucket * g.ny + 2 * g.yOff;
                    std::map<std::pair<int, int>, CSampleValue> byAbs;
                    std::set<uint32_t> distinctFilm;

                    for (int by = 0; by < kBuckets; ++by)
                        for (int bx = 0; bx < kBuckets; ++bx) {
                            const int pixelLeft = bx * kBucket, pixelTop = by * kBucket;
                            const int subLeft = pixelLeft * g.nx - g.xOff;  // reyes: bucket origin in subpixels
                            const int subTop = pixelTop * g.ny - g.yOff;
                            for (int i = 0; i < height; ++i)
                                for (int j = 0; j < width; ++j) {
                                    const int rx = CSampler::reyesAbsSub(subLeft, j), ry = CSampler::reyesAbsSub(subTop, i);
                                    const int tx = CSampler::raytraceAbsSub(pixelLeft, g.nx, g.xOff, j);
                                    const int ty = CSampler::raytraceAbsSub(pixelTop, g.ny, g.yOff, i);
                                    SP_CHECK(rx == subLeft + j && ry == subTop + i);
                                    SP_CHECK(rx == tx && ry == ty);

                                    const CSampleValue reyes = CSampler::cameraSample(cfg, rx, ry, wantLens);
                                    const CSampleValue ray = CSampler::cameraSample(cfg, tx, ty, wantLens);
                                    SP_CHECK(sameValue(reyes, ray));
                                    if (rx < 0 || ry < 0) ++negative;

                                    // What the slots define.
                                    const Expected e = expectedFor(cfg, rx, ry);
                                    SP_CHECK(close(reyes.jitterX, e.jitterX));
                                    SP_CHECK(close(reyes.jitterY, e.jitterY));
                                    SP_CHECK(close(reyes.timeStratum, e.time));
                                    SP_CHECK(close(reyes.importance, e.importance));
                                    const sp::SampleKey key = sp::cameraKey(e.id);
                                    SP_CHECK(reyes.key.full == key.full && reyes.key.path == key.path);
                                    SP_CHECK(reyes.key.pixelSampleIndex == key.pixelSampleIndex && reyes.key.kind == key.kind);

                                    // The lens point.
                                    if (!wantLens) {
                                        SP_CHECK(reyes.lensU == 0.0f && reyes.lensV == 0.0f);
                                    } else {
                                        SP_CHECK(reyes.lensU * reyes.lensU + reyes.lensV * reyes.lensV < 1.0f);
                                        const float lu = 2.0f * e.lens.u - 1.0f, lv = 2.0f * e.lens.v - 1.0f;
                                        if (lu * lu + lv * lv < 1.0f) {  // the first attempt of sampleDisk() is kept
                                            ++acceptedFirst;
                                            SP_CHECK(close(reyes.lensU, lu) && close(reyes.lensV, lv));
                                        } else {
                                            ++rejectedFirst;
                                        }
                                    }

                                    distinctFilm.insert(bitsOf(reyes.jitterX));
                                    ++checked;

                                    // A margin sample regenerated by a neighbouring bucket.
                                    const auto abs = std::make_pair(rx, ry);
                                    auto it = byAbs.find(abs);
                                    if (it == byAbs.end()) {
                                        byAbs[abs] = reyes;
                                    } else {
                                        ++shared;
                                        SP_CHECK(sameValue(it->second, reyes));
                                    }
                                }
                        }

                    // The film position really comes from the slots: with any jitter the
                    // subpixels do not all share one value.
                    if (jitter > 0.0f) SP_CHECK(distinctFilm.size() > 8);
                    // Distinct subpixels have distinct camera keys.
                    std::set<uint64_t> keys;
                    for (const auto &e : byAbs) keys.insert(e.second.key.full);
                    SP_CHECK(keys.size() == byAbs.size());
                }

    SP_CHECK(negative > 0);       // the border margin reaches negative coordinates
    SP_CHECK(shared > 0);         // neighbouring buckets do overlap
    SP_CHECK(acceptedFirst > 0);  // the lens check was exercised
    std::printf("%d subpixel samples checked, %d margin samples shared between buckets, %d with negative coordinates, "
                "lens: %d first attempts kept, %d rejected\n",
                checked, shared, negative, acceptedFirst, rejectedFirst);
}

}  // namespace

int main(int argc, char **argv) {
    return runCase(argc, argv, {{"camera_slots", cameraSlotsEqual}});
}
